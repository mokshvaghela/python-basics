# What is the type of 's'?

s = {}
print(type(s))

# Answer: <class 'dict'>
# Explanation: The curly braces {} are used to create an empty dictionary in Python. 
# Therefore, the variable 's' is of type 'dict'.
# If we wanted to create an empty set, we would use the set() function instead.
# since using {} would create an empty dictionary.