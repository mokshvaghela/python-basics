# List is used to store multiple datatypes in a single variable.
# List is mutable, which means we can change the values of the list after it is created.
# List is one type of indexing data structure.
# Which means we can access the elements of the list using their index.

# Creating a list

dataa = ["Moksh", 56, 2.6, True]
print(dataa[0]) # "Moksh"
print(dataa[1]) # 56
print(dataa[2]) # 2.6
print(dataa[3]) # True

# List slicing
print(dataa[0:2]) # ["Moksh", 56]
print(dataa[0:3]) # ["Moksh", 56, 2.6]