# \n is used to create a new line in the string
name = "Moksh is gamer and \nhe likes to play esports"
print(name)
# \t is used to create a tab space in the string
name = "Moksh is gamer and \the likes to play esports"
print(name)
# \" is used to include double quotes in the string
name = "Moksh is gamer and he likes to play \"esports\""
print(name)
# \' is used to include single quotes in the string
name = "Moksh is gamer and he likes to play \'esports\'"
# \\ is used to include backslash in the string
name = "Moksh is gamer and he likes to play esports\\"
print(name)