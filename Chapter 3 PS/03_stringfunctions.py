name = "Moksh"

print(len(name))# gives the length of the string
print(name.upper())# converts the string to uppercase
print(name.lower())# converts the string to lowercase
print(name.replace("o","a"))# replaces the first argument with the second argument in the string
print(name.count("o"))# counts the number of occurrences of the argument in the string
print(name.find("o"))# gives the index of the first occurrence of the argument in the string
