# Arithmatic Operator
# Like =, +, -, *, /
a = 7
b = 4
c = 10
d = 34
e = 33
f = a-b+c*d/e
print(f)

# Assignment Operators
# Like =, +=, -+, *=, /=
a = 26 # Assign value 26 in a
print (a)
b = 8
b += 3 # Increment the value of b by 3 and then assign into b
print (b)
c = 34
c -= 12 # Decrement the value of c by 12 and then assign into c
print (c)
# Like this we can also multiply and divide the values using this operators

# Comparison Operators
# Like ==, <=, >=, != etc
# It gives output only in boolean variable like True or False
a = 7>9
print (a)

