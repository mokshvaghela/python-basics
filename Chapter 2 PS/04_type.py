# type() function and typecasting

# Using type() function
# It is used to find which type of data is stored in variables
# It should be string, integer or float
a = "23"
t = type(a) #class variables
print (t)
b = 67
p = type(b) #class variables
print (p)
c = 77.67
y = type(c) #class variables
print (y)

# Typecasting
# It used to convert variable in another variable if possible
a = 56
b = float(a) #it convert integer into float variable using float()
print (b)
