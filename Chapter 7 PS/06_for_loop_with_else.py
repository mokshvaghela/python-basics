# for loop with else

l = [ 7, "Moksh", "Yeahhh", True, "Thala" ]

for i in l:
    print(i)
else:
    print("Loop is completed successfully.")
# The else block will be executed after the for loop completes its iteration over the list 'l'. 
# It will print the message "Loop is completed successfully." after all elements of the list have been printed.