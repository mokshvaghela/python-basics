# for loop to iterate over a sequence (like list, tuple, string) or other iterable objects.

# Example 1: Iterating over a list

l = [ 7, "Moksh", "Yeahhh", True, "Thala" ]
for i in l:
    print(i)

# Example 2: Iterating over a string

s = "Moksh Builds"
for i in s: # Here, we can also use 'char' instead of 'i' to make it more descriptive.
    print(i)

# Example 3: Iterating over a tuple

t = (1, 2, 3, 4, 5)
for i in t:
    print(i)