# While Loop in Python
# A while loop is used to execute a block of code repeatedly as long as a certain condition is true.
i = 1

while (i<6):
    print(i)
    i+=1 # This will print numbers from 1 to 5. 
# The loop will continue until i is less than 6. After each iteration, i is incremented by 1.

